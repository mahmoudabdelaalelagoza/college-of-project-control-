drop policy if exists "Public read published articles" on public.articles;
create policy "Public read published articles"
  on public.articles
  for select
  to anon, authenticated
  using (is_published = true and published_at is not null and published_at <= now());

drop policy if exists "Public read published case studies" on public.case_studies;
create policy "Public read published case studies"
  on public.case_studies
  for select
  to anon, authenticated
  using (is_published = true and published_at is not null and published_at <= now());

drop policy if exists "Public read approved testimonials" on public.testimonials;
create policy "Public read approved testimonials"
  on public.testimonials
  for select
  to anon, authenticated
  using (status = 'approved' and consent = true);

drop policy if exists "Public read visible event categories" on public.event_categories;
create policy "Public read visible event categories"
  on public.event_categories
  for select
  to anon, authenticated
  using (is_visible = true);

drop policy if exists "Public read active events" on public.events;
create policy "Public read active events"
  on public.events
  for select
  to anon, authenticated
  using (
    is_active = true
    and remote_status not in ('deleted', 'private', 'unpublished', 'missing')
    and (
      (source_is_public = true and remote_status <> 'draft')
      or (
        source = 'eventbrite'
        and remote_status = 'draft'
        and coalesce(ends_at, starts_at) > now()
      )
    )
  );

drop policy if exists "Public read event classifications" on public.event_classifications;
create policy "Public read event classifications"
  on public.event_classifications
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public submit enquiries" on public.enquiries;
create policy "Public submit enquiries"
  on public.enquiries
  for insert
  to anon, authenticated
  with check (
    length(trim(name)) > 0
    and email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'
    and status = 'new'
  );
