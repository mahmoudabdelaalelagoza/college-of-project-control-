-- Supabase public-content schema, phase 1.
-- Applies the first frontend migration batch:
-- ipc_images, partners, sectors.
--
-- Run this in the Supabase SQL editor after reviewing names and policies.
-- Public visitors can read active rows only. Writes stay blocked for anon users.

create table if not exists public.ipc_images (
  id bigint generated by default as identity primary key,
  image_url text not null,
  alt_text text not null default '',
  "order" integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

