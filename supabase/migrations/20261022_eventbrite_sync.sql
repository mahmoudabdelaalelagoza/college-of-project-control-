-- Eventbrite connection settings and sync history for the eventbrite-sync Edge Function.
-- Only the Edge Function (service role) reads or writes these tables; RLS is on with no policies,
-- so the encrypted token is never exposed to the browser.

create table if not exists public.eventbrite_settings (
  id integer primary key default 1 check (id = 1),
  private_token_encrypted text,
  organization_id text,
  organization_name text,
  public_backend_url text,
  sync_interval_minutes integer not null default 15,
  auto_sync_enabled boolean not null default true,
  show_uncategorized boolean not null default true,
  connection_status text not null default 'unverified',
  last_test_at timestamptz,
  last_full_sync_at timestamptz,
  last_sync_status text,
  updated_at timestamptz not null default now()
);

insert into public.eventbrite_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.eventbrite_sync_jobs (
  id bigint generated by default as identity primary key,
  sync_type text not null default 'manual',
  status text not null default 'running',
  trigger_source text not null default 'dashboard',
  fetched_count integer not null default 0,
  created_count integer not null default 0,
  updated_count integer not null default 0,
  removed_count integer not null default 0,
  message text,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists eventbrite_sync_jobs_created_at_idx on public.eventbrite_sync_jobs (created_at desc);

alter table public.eventbrite_settings enable row level security;
alter table public.eventbrite_sync_jobs enable row level security;
